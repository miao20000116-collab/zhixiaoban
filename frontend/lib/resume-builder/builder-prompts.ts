// ==================== 2. 模板推荐 ====================

export function buildTemplateRecommendPrompt(
  data: any,
  templates: { id: string; name: string; desc: string; ats: string; suitable: string[] }[]
): string {
  return `根据用户的简历数据，推荐 4-5 套最适合的模板。

考虑因素：
- ATS 友好度：大公司/海投优先推荐 ATS 友好的
- 岗位风格：技术岗紧凑型，设计岗视觉型，产品岗信息卡型
- 经历厚度：经历丰富推荐 Timeline/Executive，简洁推荐 Atelier

用户数据：
${JSON.stringify(data, null, 2)}

可用模板：
${JSON.stringify(templates, null, 2)}

输出 JSON（不要 markdown 代码块）：
{"reasoning":"简要说明","recommended":["id1","id2","id3","id4"]}`
}

// ==================== 3. 模板渲染 ====================

export function buildRenderPrompt(data: any, _templateId: string, templateHtml: string): string {
  return `你是一位简历 HTML 渲染专家。

## 任务
将用户的结构化简历数据，填入指定的 HTML 模板中，输出可直接在浏览器预览和打印的完整简历 HTML。

## 规则
1. **保留模板的 <style> 完全不动**
2. **把模板中的示例内容替换为用户真实数据**
3. **没有的板块整块删除**
4. **一页优先，内容太多时精简 bullet**
5. **保持原有 HTML 结构（class、布局 div 等）不变**

## 用户数据
${JSON.stringify(data, null, 2)}

## 模板 HTML
${templateHtml}

直接输出完整 HTML，不要 markdown 代码块，不要额外说明。`
}
